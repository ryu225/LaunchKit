CREATE DATABASE IF NOT EXISTS launchkit CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE launchkit;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sites (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 business_name VARCHAR(120) NOT NULL,
 slug VARCHAR(80) NOT NULL UNIQUE,
 tagline VARCHAR(200) NOT NULL DEFAULT '',
 description TEXT NOT NULL,
 services TEXT NOT NULL,
 contact VARCHAR(190) NOT NULL DEFAULT '',
 template ENUM('classic','playful','minimal') NOT NULL DEFAULT 'classic',
 color VARCHAR(7) NOT NULL DEFAULT '#d84937',
 secondary_color VARCHAR(7) NOT NULL DEFAULT '#fff2e6',
 text_color VARCHAR(7) NOT NULL DEFAULT '#252021',
 logo_path VARCHAR(220) NOT NULL DEFAULT '',
 business_type VARCHAR(25) NOT NULL DEFAULT 'other',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_sites_user (user_id)
) ENGINE=InnoDB;
